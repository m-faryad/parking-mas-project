"""Replicated, paired experiment runner.

For every scenario and replication r the seed is ``base_seed + 1000*scenario_index + r``.
Both strategies are run on the *same generated arrival stream* (same seed, same
DataFrame object), so the comparison is paired and differences are due to the
allocation strategy only.
"""

from __future__ import annotations

import dataclasses
import json
import platform
import sys
import time
from collections.abc import Callable
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
import scipy

from . import __version__
from .config import STRATEGIES, ConfigError, ScenarioConfig, save_config
from .datagen import generate_arrivals
from .engine import Simulation
from .metrics import compute_metrics, occupancy_timeseries

RUN_KEYS = ["scenario", "strategy", "replication", "seed"]


def seed_for(base_seed: int, scenario_index: int, replication: int) -> int:
    return int(base_seed) + 1000 * scenario_index + replication


def run_one(cfg: ScenarioConfig, strategy: str, arrivals: pd.DataFrame | None = None,
            keep_details: bool = False) -> dict:
    """Run one simulation; returns metrics, occupancy time series (+ decision/event logs)."""
    t0 = time.perf_counter()
    sim = Simulation(cfg, strategy, arrivals=arrivals).run()
    m = compute_metrics(sim)
    m["wall_clock_s"] = round(time.perf_counter() - t0, 4)  # non-deterministic, informational
    out = {"metrics": m, "occupancy": occupancy_timeseries(sim)}
    if keep_details:
        out["decisions"] = pd.DataFrame(sim.decisions)
        out["events"] = pd.DataFrame(sim.events)
        out["vehicles"] = sim.vehicle_table()
        out["arrivals"] = sim.arrivals
    return out


def run_experiment(scenarios: list[ScenarioConfig], replications: int, base_seed: int, out_dir: str | Path,
                   strategies: tuple[str, ...] = STRATEGIES, mode: str = "custom", overwrite: bool = False,
                   progress: Callable[[int, int, str], None] | None = None) -> Path:
    """Run the full experiment grid and persist raw results under ``out_dir``."""
    if replications < 1:
        raise ConfigError("replications must be >= 1")
    if not scenarios:
        raise ConfigError("at least one scenario is required")
    for s in scenarios:
        s.validate()
    out = Path(out_dir)
    if out.exists() and any(out.iterdir()) and not overwrite:
        raise FileExistsError(f"{out} already contains results (use overwrite=True / --overwrite)")
    out.mkdir(parents=True, exist_ok=True)
    (out / "scenarios").mkdir(exist_ok=True)
    runs, occ, decisions = [], [], []
    total = len(scenarios) * replications * len(strategies)
    done = 0
    t_start = time.perf_counter()
    for si, base_cfg in enumerate(scenarios):
        save_config(base_cfg, out / "scenarios" / f"{base_cfg.name}.json")
        for r in range(replications):
            seed = seed_for(base_seed, si, r)
            cfg = dataclasses.replace(base_cfg, seed=seed)
            arrivals = generate_arrivals(cfg)  # shared by all strategies => paired comparison
            for st in strategies:
                res = run_one(cfg, st, arrivals, keep_details=(r == 0))
                m = res["metrics"]
                m.update({"replication": r, "mode": mode})
                runs.append(m)
                ts = res["occupancy"].copy()
                for k, v in (("scenario", cfg.name), ("strategy", st), ("replication", r), ("seed", seed)):
                    ts[k] = v
                occ.append(ts)
                if r == 0:
                    d = res["decisions"].copy()
                    d.insert(0, "scenario", cfg.name)
                    decisions.append(d)
                done += 1
                if progress:
                    progress(done, total, f"{cfg.name} rep {r + 1}/{replications} {st}")
    runs_df = pd.DataFrame(runs)
    lead = [c for c in RUN_KEYS if c in runs_df.columns]
    runs_df = runs_df[lead + [c for c in runs_df.columns if c not in lead]]
    runs_df.to_csv(out / "runs.csv", index=False)
    occ_df = pd.concat(occ, ignore_index=True)
    occ_df = occ_df[RUN_KEYS + [c for c in occ_df.columns if c not in RUN_KEYS]]
    occ_df.to_csv(out / "occupancy_timeseries.csv", index=False)
    if decisions:
        pd.concat(decisions, ignore_index=True).to_csv(out / "decision_log_replication0.csv", index=False)
    meta = {
        "data_origin": "SYNTHETIC - generated by parking_mas.datagen; not collected from any real car park",
        "package_version": __version__,
        "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "mode": mode,
        "scenarios": [s.name for s in scenarios],
        "strategies": list(strategies),
        "replications": replications,
        "base_seed": base_seed,
        "seed_rule": "seed = base_seed + 1000*scenario_index + replication; strategies share the arrival stream",
        "n_runs": len(runs_df),
        "total_wall_clock_s": round(time.perf_counter() - t_start, 2),
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "numpy": np.__version__, "pandas": pd.__version__, "scipy": scipy.__version__,
        "nondeterministic_columns": ["wall_clock_s", "mean_decision_ms"],
    }
    (out / "metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return out
